/** Interpolation-aware — {name} placeholders in a template get swapped for the
 * matching var. Used for combat log lines and anything else built from a template
 * plus dynamic values, so translated strings don't need per-callsite string
 * concatenation logic duplicated in two languages. */
function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

